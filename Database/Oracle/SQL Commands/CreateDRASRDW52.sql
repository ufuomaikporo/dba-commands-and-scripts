-- Prompt user to set the SYS and SYSTEM passwords

SET VERIFY OFF
ACCEPT sysPassword CHAR PROMPT 'Enter new password for SYS: ' HIDE
ACCEPT systemPassword CHAR PROMPT 'Enter new password for SYSTEM: ' HIDE

SPOOL %ORACLE_BASE%\admin\DBCreationSpoolFile.log REPLACE
------------------------------------------------------ CREATE DATABASE -----------------------------------------------------------

CREATE DATABASE UFODB -- 8 character limit for database name
USER SYS IDENTIFIED BY "&&sysPassword"
USER SYSTEM IDENTIFIED BY "&&systemPassword"
-- Multiplexed Redo log files
LOGFILE GROUP 1 ('D:\Oracle\DRASRDW52\Data\redo01.log') SIZE 200M,
	   GROUP 2 ('D:\Oracle\DRASRDW52\Data\redo02.log') SIZE 200M,
	   GROUP 3 ('D:\Oracle\DRASRDW52\Data\redo03.log') SIZE 200M
MAXLOGFILES 5
MAXLOGMEMBERS 5
MAXLOGHISTORY 1
MAXDATAFILES 100
MAXINSTANCES 1
CHARACTER SET AL32UTF8
NATIONAL CHARACTER SET AL16UTF16
EXTENT MANAGEMENT LOCAL
-- Create data files
DATAFILE 'D:\Oracle\DRASRDW52\Data\system01.dbf' 
	SIZE 880M REUSE AUTOEXTEND ON NEXT 200M MAXSIZE UNLIMITED
SYSAUX DATAFILE 'D:\Oracle\DRASRDW52\Data\sysaux01.dbf' 
	SIZE 500M REUSE AUTOEXTEND ON NEXT 100M MAXSIZE UNLIMITED
DEFAULT TABLESPACE users
DATAFILE 'D:\Oracle\DRASRDW52\Data\users01.dbf'
	SIZE 500M REUSE AUTOEXTEND ON NEXT 200M MAXSIZE UNLIMITED
DEFAULT TEMPORARY TABLESPACE TEMP
TEMPFILE 'D:\Oracle\DRASRDW52\Data\temp01.dbf'
	SIZE 100M REUSE AUTOEXTEND ON NEXT 20M MAXSIZE UNLIMITED
UNDO TABLESPACE UNDOTBS
 DATAFILE 'D:\Oracle\DRASRDW52\Data\undotbs01.dbf'
  SIZE 700M REUSE AUTOEXTEND ON NEXT 200M MAXSIZE UNLIMITED;

----------------------------------- Install Oracle components in CDB$ROOT and PDB$SEED ---------------------------

CONNECT SYS/"&&SYSPASSWORD" AS SYSDBA

@?\RDBMS\ADMIN\CATALOG.SQL
@?\RDBMS\ADMIN\CATPROC.SQL
@?\RDBMS\ADMIN\UTLRP.SQL

CONNECT SYSTEM/"&&SYSTEMPASSWORD"

@?\SQLPLUS\ADMIN\PUPBLD.SQL

SPOOL OFF