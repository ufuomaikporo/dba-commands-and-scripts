-- ADDREVERSEDFLAGTORANGE.SQL

-- 0 = DEFAULT 1 = REVERSED
-- THEN SETS REVERSED STATE TO CURRENT STATE OF THE INLINEINSPECTION TO UPDATE HISTORICAL RECORDS

DECLARE CNT INT;
BEGIN

    SELECT COUNT(*) INTO CNT FROM USER_TAB_COLUMNS 
    WHERE UPPER(TABLE_NAME) = UPPER('INLINEINSPECTIONRANGE') 
    AND UPPER(COLUMN_NAME) = UPPER('REVERSED');

    IF CNT = 0
    THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INLINEINSPECTIONRANGE ADD REVERSED NUMBER(1,0) DEFAULT 0';
        EXECUTE IMMEDIATE 'MERGE INTO INLINEINSPECTIONRANGE R
                            USING (SELECT ID, REVERSEDORDER FROM INLINEINSPECTION) I
                            ON (I.ID = R.INLINEINSPECTIONID)
                            WHEN MATCHED THEN
                            UPDATE SET R.REVERSED = I.REVERSEDORDER';
    END IF;
END;
