/*

This script will generate code to create DomainCatalog Descr and DomainCatalogColXRef entries based on what is in the  
DRAS_IRASv6_DEMO_QA_6_5_1 database. You need to replace the ##FlaggedTables_64 table with a table that contains the tables 
and columns that are missing a DomainCatalogColXRef entry. ##FlaggedTables_64 table can be generated by the 6.5.0 script (if you remove transaction block) 
or by running the FlagListDomainConflicts_4_IRAS_6.5.0_Upgrade.sql script on the target db
*/

WITH CTE AS(
select tld.TableName, tld.ColumnName, tld.DomainDescr from DRASSQL2017.DRAS_IRASv6_DEMO_QA_6_5_1.dbo.TempListDomainTable tld
LEFT JOIN  ##FlaggedTables_64 ft 
ON ft.TableName = tld.TableName AND ft.ColumnName = tld.ColumnName 
)SELECT cte.TableName, cte.ColumnName, dc.Id, dc.DomainDescr, cte.DomainDescr,
'IF NOT EXISTS (SELECT * FROM DomainCatalogColXRef WHERE TableName = ''' + cte.TableName + ''' AND ColumnName = ''' + cte.ColumnName + ''')
BEGIN
INSERT INTO DomainCatalogColXRef (TableName, ColumnName, DomainCatalogId)
SELECT ''' + cte.TableName + ''', ''' + cte.ColumnName + ''', Id FROM DomainCatalog WHERE DomainDescr = ''' + cte.DomainDescr + '''
END' AS Add_to_DomainCatalogColXRef,
'IF NOT EXISTS (SELECT * FROM DomainCatalog WHERE DomainDescr = ''' + cte.DomainDescr + ''')
BEGIN
	INSERT INTO DomainCatalog (Id, DomainDescr)
	SELECT MAX(Id) + 1, ''' + cte.DomainDescr + ''' FROM DomainCatalog
END' Add_New_DomainDescr
FROM CTE 
LEFT JOIN DomainCatalog dc ON dc.DomainDescr = cte.DomainDescr